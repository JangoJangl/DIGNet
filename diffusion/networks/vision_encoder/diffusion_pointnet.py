class Diffusion_Pointnet2(nn.Module):
    def __init__(self, output_dim=128, x_dim=7, diffusion_steps=5, radius=0.1, max_radius=0.4, max_npoint=500, max_nsample=200,
                 min_dim=128, max_dim=1024, t_dim=32, device='cuda:0'):
        '''
        PointNet2 with hierarchical feature extraction
        :param output_dim: output dimension of the network
        :param diffusion_steps: number of diffusion steps and number of layers in the network
        :param radius: radius for the local region set to the maximum gripper width
        '''
        super(Diffusion_Pointnet2, self).__init__()
        in_channel = t_dim  # time embedding for diffusion step
        # (npoint, radius_list, nsample_list, in_channel, mlp_list):
        self.device = device
        self.output_dim = output_dim
        self.diffusion_steps = diffusion_steps
        radius_list = [radius + (max_radius - radius) * i / (diffusion_steps-2) for i in range(diffusion_steps-1)]
        npoint_list = [round(max_npoint * (i+1) / (diffusion_steps-1)) for i in range(diffusion_steps-1)]
        npoint_list.reverse()
        nsample_list = [round(max_nsample) if max_nsample < (i+1) * max_npoint / diffusion_steps else round(max_npoint / (diffusion_steps-1))
                        for i in range(diffusion_steps-1)]
        # interpolate the dimension in log2 space linearly
        log_dist = math.log2(max_dim) - math.log2(min_dim)
        decoder_log_dist = math.log2(output_dim) - math.log2(x_dim)
        dim_list = [int(2 ** (math.log2(min_dim) + log_dist * i / (diffusion_steps - 2))) for i in range(diffusion_steps- 1)]
        decoder_dim = [int(2 ** (math.log2(x_dim) + decoder_log_dist * i / (diffusion_steps - 2))) for i in reversed(range(diffusion_steps- 1))]
        self.temp_layers = nn.Sequential(
            SinusoidalPosEmb(t_dim),
            nn.Linear(t_dim, t_dim * 2),
            nn.Mish(),
            nn.Linear(t_dim * 2, t_dim),
        )
        self.temp_layers.to(self.device)
        self.sa_list = nn.ModuleList()
        self.decoder_list = nn.ModuleList()

        for layer in range(diffusion_steps-1):
            self.sa_list.append(PointNetSetAbstractionMsg(npoint_list[layer],
                                                          [radius_list[layer] / 4, radius_list[layer] / 2,
                                                           radius_list[layer]],
                                                          [nsample_list[layer] // 4, nsample_list[layer] // 2,
                                                           nsample_list[layer]], in_channel,
                                                          [[dim_list[layer] // 4, dim_list[layer] // 4, dim_list[layer] // 2],
                                                           [dim_list[layer] // 4, dim_list[layer] // 4,
                                                            dim_list[layer] // 2],
                                                           [dim_list[layer] // 2, dim_list[layer] // 2,
                                                            dim_list[layer]]]))

            in_channel = dim_list[layer] * 2
        self.sa_list.append(PointNetSetAbstraction(None, None, None, 2*dim_list[-1] + 3,
                                   [self.output_dim * 4, self.output_dim * 2, self.output_dim], True))
        in_channel = self.output_dim
        for dim in decoder_dim:
            self.decoder_list.append(torch.nn.Linear(in_channel, dim))
            in_channel = dim



    def forward(self, xyz, t):
        xyz = torch.transpose(xyz, 1, 2)  # (B, N, 3) -> (B, 3, N) for input to PointNet2
        B, _, _ = xyz.shape

        time_embedding = self.temp_layers(t)
        features = time_embedding.view(B, -1, 1).repeat(1, 1, xyz.shape[2])
        for i, layer in enumerate(self.sa_list):
            xyz, features = layer(xyz, features)
        features = features.view(B, -1)
        for layer in self.decoder_list:
            features = F.silu(layer(features))


        return features # returns the x_(t-1)

    def compute_features(self, condition, t, position):

        # most global features are incapsulated in the pointnet output
        if t.shape[0] == 1:
            condition = [condition[t]]
        else:
            condition = [condition[t[i]] for i in range(t.shape[0])]
        embedding = torch.empty((0, self.output_dim), device='cuda:0')
        for i, condition_tuple in enumerate(condition):
            (xyz, features) = condition_tuple
            dists = square_distance(position[i, :].view(1,1,3), xyz)
            idx = torch.argmin(dists, -1)
            embedding = torch.cat((embedding, features[idx, :].view(-1, self.output_dim)), dim=0)


        return embedding




